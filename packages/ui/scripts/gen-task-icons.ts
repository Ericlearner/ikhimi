/**
 * Bundles the few Fluent Emoji (Iconify set fluent-emoji-flat, MIT, Microsoft) the homework UI uses into
 * src/task-icons.generated.ts. Offline and instant: no runtime fetch from api.iconify.design, which would be
 * slow on 3G and blank when offline. Add a name to ICONS and run `pnpm --filter @ikhimi/ui icons`.
 */
import { writeFileSync } from 'node:fs'
import { getIconData, iconToSVG } from '@iconify/utils'
import set from '@iconify-json/fluent-emoji-flat/icons.json' with { type: 'json' }

export const ICONS = [
  'bullseye', 'check-mark-button', 'balance-scale', 'pencil', 'puzzle-piece', 'input-numbers', 'writing-hand', 'headphone',
  'cross-mark', 'light-bulb', 'fire', 'trophy', 'glowing-star', 'star', 'flexed-biceps', 'open-book', 'party-popper',
  'sparkles', 'books', 'memo', 'speech-balloon', 'brain', 'rocket', 'hundred-points', 'clapping-hands', 'graduation-cap',
  'studio-microphone', 'spiral-notepad', 'sports-medal', 'thumbs-up', 'books', 'keyboard', 'owl', 'stopwatch', 'chart-increasing',
] as const

/** Deterministic id prefixing (the library's replaceIDs randomises, which would churn this file) */
function prefixIds(body: string, prefix: string) {
  const ids = [...body.matchAll(/\bid="([^"]+)"/g)].map((m) => m[1]!)
  let out = body
  for (const id of ids) {
    const esc = id.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    out = out
      .replace(new RegExp(`\\bid="${esc}"`, 'g'), `id="${prefix}${id}"`)
      .replace(new RegExp(`url\\(#${esc}\\)`, 'g'), `url(#${prefix}${id})`)
      .replace(new RegExp(`href="#${esc}"`, 'g'), `href="#${prefix}${id}"`)
  }
  return out
}

const out: Record<string, { body: string; viewBox: string }> = {}
for (const name of new Set(ICONS)) {
  const data = getIconData(set as never, name)
  if (!data) throw new Error(`missing icon ${name}`)
  const svg = iconToSVG(data)
  // Gradient ids made unique per icon so several icons on one page never collide
  out[name] = { body: prefixIds(svg.body, `ti-${name}-`), viewBox: svg.attributes.viewBox }
}
writeFileSync(
  new URL('../src/task-icons.generated.ts', import.meta.url),
  `// Generated by scripts/gen-task-icons.ts from @iconify-json/fluent-emoji-flat (MIT). Do not edit.\n` +
    `export const TASK_ICONS = ${JSON.stringify(out)} as const\nexport type TaskIconName = keyof typeof TASK_ICONS\n`,
)
console.log(`${Object.keys(out).length} icons, ${JSON.stringify(out).length} bytes`)
